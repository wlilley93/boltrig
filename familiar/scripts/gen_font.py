# Index order IS the shader's glyph id. Keep it stable: the label tables in
# jarvis.frag are written against these numbers.
ORDER = list("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .-")


def pack(rows):
    lo = hi = 0
    for n, row in enumerate(rows):
        bits = int(row, 2)
        if n < 4:
            lo |= bits << (5 * n)
        else:
            hi |= bits << (5 * (n - 4))
    return lo, hi


def main():
    for name, rows in GLYPHS.items():
        assert len(rows) == 7, f"{name}: expected 7 rows, got {len(rows)}"
        for row in rows:
            assert len(row) == 5 and set(row) <= {"0", "1"}, f"{name}: bad row {row!r}"

    n = len(ORDER)
    lines = [
        "// ---------------------------------------------------------------------------",
        "// GLYPH ATLAS  (generated - see scripts/gen_font.py, do not hand-edit)",
        "//",
        "// 5x7 uppercase bitmap font, one uvec2 per glyph: .x holds rows 0..3 and .y",
        "// rows 4..6, each row 5 bits with the MSB leftmost. Indices are the glyph ids",
        "// the label tables below are written against:",
        "//   0..25  A-Z      26..35  0-9      36 space   37 period   38 hyphen",
        "// ---------------------------------------------------------------------------",
        f"const int GLYPH_COUNT = {n};",
        f"const uvec2 FONT[{n}] = uvec2[{n}](",
    ]
    for i, ch in enumerate(ORDER):
        lo, hi = pack(GLYPHS[ch])
        comma = "," if i < n - 1 else ""
        label = "space" if ch == " " else ch
        lines.append(f"    uvec2(0x{lo:05X}u, 0x{hi:04X}u){comma:<1}  // {i:2d}  {label}")
    lines.append(");")

    out = "\n".join(lines) + "\n"
    import sys
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
